// Extracts the Health & Safety tab's 8 "common mistakes" cards (plus their
// closing disclaimer paragraph) from index.html's #health-mistakes block,
// verbatim (never retyped) - same cheerio-based pattern as
// scripts/extract-about.js / scripts/extract-activities.js /
// scripts/extract-faq.js.
//
// Unlike those, this data has no dedicated js/corfu-*.js source file to
// regenerate: editorial.healthSafety already lives directly inline inside
// data/destinations/corfu.js (see that file's own header comment - it only
// pulls the BIG data sets like locations/itinerary/faq out to their own
// files; healthSafety's emergencyNumbers/hospitals/etc. were hand-migrated
// in place). So this script extends healthSafety in place too: it inserts
// two new fields, `commonMistakes` and `commonMistakesDisclaimer`, right
// after the existing `insuranceReminderHtml` field, by matching that
// field's exact current text as a unique anchor. It refuses to run (throws,
// writes nothing) if the anchor isn't found or isn't unique, rather than
// silently corrupting the file.
//
// Re-run after any hand-edit to the #health-mistakes source markup in
// index.html. Do not hand-edit the commonMistakes/commonMistakesDisclaimer
// fields in data/destinations/corfu.js directly.
//
// Usage: node scripts/extract-health-mistakes.js
'use strict';

const fs = require('fs');
const path = require('path');
const cheerio = require('cheerio');

const ROOT = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const $ = cheerio.load(html);

const cards = $('#health-mistakes > div.grid > div');

const commonMistakes = [];
cards.each((i, el) => {
    const $el = $(el);
    const titleFull = $el.find('p').eq(0).text().trim();
    const description = $el.find('p').eq(1).text().trim();
    const emojiMatch = titleFull.match(/^(\S+)\s*/);
    const icon = emojiMatch ? emojiMatch[1] : '';
    const title = titleFull.replace(/^\S+\s*/, '').trim();

    // Two of the 8 original cards use a differently-styled container
    // (gt-bg-sunken/gt-text-900 instead of the other six's
    // gt-bg-accent-soft/gt-text-accent) - actually just checked: exactly
    // ONE does (the "shops close for siesta" card). No content-based
    // pattern explains it (other logistics/practical-tip cards, e.g. the
    // car-rental and credit-card ones, use the standard style) - it reads
    // as an incidental one-off rather than a deliberate "this one's more
    // important" signal, but it's a real, currently-visible style
    // difference, so it's preserved as an explicit per-item flag rather
    // than silently normalized away.
    const item = { icon, title, description };
    if ($el.hasClass('gt-bg-sunken')) {
        item.variant = 'sunken';
    }
    commonMistakes.push(item);
});

if (commonMistakes.length !== 8) {
    throw new Error(`extract-health-mistakes: expected 8 mistake cards, found ${commonMistakes.length} - aborting, not writing a possibly-truncated file`);
}

const commonMistakesDisclaimer = $('#health-mistakes > p').first().text().trim();
if (!commonMistakesDisclaimer) {
    throw new Error('extract-health-mistakes: expected a non-empty disclaimer paragraph - aborting');
}

// --- Splice the extracted data into data/destinations/corfu.js's existing
// editorial.healthSafety object, right after insuranceReminderHtml. ---
const corfuJsPath = path.join(ROOT, 'data/destinations/corfu.js');
const corfuJs = fs.readFileSync(corfuJsPath, 'utf8');

const anchor = "insuranceReminderHtml: '💡 טיפ חשוב: זכרו תמיד ליצור קשר עם מוקד החירום של חברת ביטוח הנסיעות שלכם מיד לפני או אחרי קבלת טיפול רפואי להסדרת התשלומים!'";
const anchorCount = corfuJs.split(anchor).length - 1;
if (anchorCount !== 1) {
    throw new Error(`extract-health-mistakes: expected exactly 1 occurrence of the insuranceReminderHtml anchor in data/destinations/corfu.js, found ${anchorCount} - aborting, not writing`);
}

const mistakesBlock = JSON.stringify(commonMistakes, null, 2).split('\n').join('\n            ');

const insertion = `${anchor},

            // Auto-generated by scripts/extract-health-mistakes.js from
            // index.html's #health-mistakes block. Do not hand-edit lightly
            // — regenerate via the script if the source markup changes. See
            // that script's header for the gt-bg-sunken \`variant\` note.
            commonMistakes: ${mistakesBlock},
            commonMistakesDisclaimer: ${JSON.stringify(commonMistakesDisclaimer)}`;

const updatedCorfuJs = corfuJs.replace(anchor, insertion);

fs.writeFileSync(corfuJsPath, updatedCorfuJs, 'utf8');
console.log(`Extracted ${commonMistakes.length} common-mistake cards + disclaimer -> data/destinations/corfu.js`);
commonMistakes.forEach(m => console.log(`  ${m.icon} ${m.title}${m.variant ? ` (variant: ${m.variant})` : ''}`));
