// Extracts the About tab's 6 "quick facts" pills from index.html and adds
// them to js/corfu-about.js as a new `quickFacts` field alongside the
// existing `regions` array (same file, same window.CORFU_ABOUT object) -
// same cheerio-based pattern as scripts/extract-about.js.
//
// A separate script rather than folded into scripts/extract-about.js: the
// region-card markup that script reads from index.html was already
// replaced, in an earlier migration round, by the empty
// #about-regions-grid container (see index.html) - so extract-about.js can
// no longer be re-run against the live page (it would find 0 region cards
// and abort). This script instead extracts only the still-present
// quick-facts markup and merges it into the region data that already lives
// in js/corfu-about.js, verbatim, without hand-retyping either half.
//
// Usage: node scripts/extract-about-quickfacts.js
'use strict';

const fs = require('fs');
const path = require('path');
const cheerio = require('cheerio');

const ROOT = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const $ = cheerio.load(html);

// The existing regions data (already extracted+migrated by
// scripts/extract-about.js in an earlier round) - read back out of the
// current js/corfu-about.js so it can be carried forward unchanged rather
// than hand-retyped.
const aboutPath = path.join(ROOT, 'js/corfu-about.js');
const existingSrc = fs.readFileSync(aboutPath, 'utf8');
const sandbox = { window: {} };
// eslint-disable-next-line no-new-func
new Function('window', existingSrc)(sandbox.window);
const regions = sandbox.window.CORFU_ABOUT && sandbox.window.CORFU_ABOUT.regions;
if (!Array.isArray(regions) || regions.length !== 4) {
    throw new Error(`extract-about-quickfacts: expected to read back 4 existing regions from js/corfu-about.js, found ${regions && regions.length} - aborting`);
}

// Quick-facts pills - the row of 6 <span> chips right under the About tab's
// hero divider. Each pill is either "emoji + text" or (the currency pill
// only) "inline <svg class="icon-line"> + text". Modelled as {icon, text}
// for the emoji pills and {iconHtml, text} for the svg pill: `icon` is
// plain text and gets HTML-escaped by the renderer, `iconHtml` is raw
// markup and must NOT be escaped (escaping the svg's `<`/`>` would break
// it) - same icon/iconHtml split convention as other raw-markup fields
// (e.g. editorial.healthSafety.insuranceReminderHtml).
const quickFacts = [];
$('#about div.max-w-5xl.mx-auto.flex.flex-wrap.justify-center.gap-2\\.5 > span').each((i, el) => {
    const $el = $(el);
    const svg = $el.find('svg').first();
    const fullText = $el.text().trim();
    if (svg.length) {
        quickFacts.push({ iconHtml: $.html(svg), text: fullText });
    } else {
        const emojiMatch = fullText.match(/^(\S+)\s*/);
        const icon = emojiMatch ? emojiMatch[1] : '';
        const text = fullText.replace(/^\S+\s*/, '').trim();
        quickFacts.push({ icon, text });
    }
});

if (quickFacts.length !== 6) {
    throw new Error(`extract-about-quickfacts: expected 6 quick-facts pills, found ${quickFacts.length} - aborting, not writing a possibly-truncated file`);
}

const out = `// Auto-generated by scripts/extract-about.js (regions) and
// scripts/extract-about-quickfacts.js (quickFacts) from the original
// index.html. Do not hand-edit lightly — regenerate via those scripts if
// the source markup changes. Note: regions can no longer be re-extracted
// from a live index.html (that markup was replaced by the empty
// #about-regions-grid container in an earlier migration round) -
// extract-about-quickfacts.js carries the existing regions array forward
// unchanged when regenerating this file.
window.CORFU_ABOUT = {
  regions: ${JSON.stringify(regions, null, 2).split('\n').join('\n  ')},
  quickFacts: ${JSON.stringify(quickFacts, null, 2).split('\n').join('\n  ')}
};
`;

fs.writeFileSync(aboutPath, out, 'utf8');
console.log(`Carried forward ${regions.length} region cards + extracted ${quickFacts.length} quick-facts pills -> js/corfu-about.js`);
quickFacts.forEach(q => console.log(`  pill: ${q.icon || '(svg)'} ${q.text}`));
